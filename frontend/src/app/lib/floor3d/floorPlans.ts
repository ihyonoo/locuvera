// 층별 3D 도면 데이터 — 원본 안내도 이미지(public/images/floor-maps, 930×976 px) 좌표.
// 구역 폴리곤은 넣지 않는다: floorZoneBounds.ts(zones.py 생성물)를 px로 바꿔 쓴다.
// 외벽·코어·실은 미리보기 단계에서 원본 이미지에 겹쳐 따고 검증했다(docs/design/2026-10-30-floor-map-3d.md).
import type { FloorNumber } from '../floorMaps';
import type { ZonePoint } from '../floorZoneBounds';
import type { Px } from './layout';

export type ZoneLabel = { at: Px; lines: string[] };
export type Room = {
  poly: Px[];
  name?: string;
  lines?: string[];
  at?: Px;
  kind?: 'office' | 'pharmacy' | 'waiting' | 'clinic' | 'cafe';
};
// 종류, x1, y1, x2, y2 — EV 승강기, ST 계단, ES 에스컬레이터, WC 화장실
export type Core = ['EV' | 'ST' | 'ES' | 'WC', number, number, number, number];
export type PlanLabel = { text: string; at: Px; kind: 'gate' | 'amenity' | 'area' };
export type FloorPlan = {
  floor: FloorNumber;
  title: string;
  // 손으로 딴 구역 꼭짓점을 붙일 벽선 좌표
  snap?: { x: number[]; y: number[] };
  outline: Px[];
  zoneLabels: Record<string, ZoneLabel>;
  rooms: Room[];
  service: Px[][];
  cores: Core[];
  walls: Px[][];
  railings: Px[][];
  labels: PlanLabel[];
};

const IMAGE_W = 930;
const IMAGE_H = 976;
const SNAP_TOLERANCE = 3.2;

// 리더 ID 규칙 M<층><번호> — 'M208' → 2층
export function readerFloor(readerId: string): FloorNumber | null {
  const match = /^M([1-5])\d{2}$/.exec(readerId);
  return match ? (Number(match[1]) as FloorNumber) : null;
}

const toPx = (percent: number, size: number) => Math.round((percent * size) / 10) / 10;
const snapTo = (value: number, lines: number[] | undefined) =>
  lines?.find((line) => Math.abs(line - value) <= SNAP_TOLERANCE) ?? value;

// 이 층 리더 구역의 폴리곤(퍼센트)을 이미지 px로 바꾸고 벽선에 붙인다
export function zonePolygonsPx(
  plan: FloorPlan,
  zoneBounds: Record<string, ZonePoint[]>,
): { readerId: string; poly: Px[] }[] {
  return Object.entries(zoneBounds)
    .filter(([readerId]) => readerFloor(readerId) === plan.floor)
    .map(([readerId, polygon]) => ({
      readerId,
      poly: polygon.map(({ x, y }): Px => [
        snapTo(toPx(x, IMAGE_W), plan.snap?.x),
        snapTo(toPx(y, IMAGE_H), plan.snap?.y),
      ]),
    }));
}

